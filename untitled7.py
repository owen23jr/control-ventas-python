import csv
import os
import math

ARCHIVO = "ventas.csv"
CAMPOS = ["producto", "cantidad", "ingreso", "gasto", "ganancia"]


def cargar_ventas():
    if not os.path.exists(ARCHIVO):
        return []

    with open(ARCHIVO, "r", newline="", encoding="utf-8-sig") as archivo:
        return list(csv.DictReader(archivo))


ventas = cargar_ventas()


def registrar_venta():
    producto = input("Producto: ").strip()

    if not producto:
        print("Escribe el nombre del producto.")
        return

    try:
        precio = float(input("Precio de venta por unidad: "))
        costo = float(input("Costo por unidad: "))
        cantidad = int(input("Cantidad vendida: "))

        if not math.isfinite(precio) or not math.isfinite(costo):
            print("Introduce precios validos.")
            return

        if precio < 0 or costo < 0 or cantidad <= 0:
            print("Precios no negativos y cantidad mayor que cero.")
            return

    except ValueError:
        print("Revisa los datos introducidos.")
        return

    venta = {
        "producto": producto,
        "cantidad": cantidad,
        "ingreso": precio * cantidad,
        "gasto": costo * cantidad,
        "ganancia": (precio - costo) * cantidad
    }

    with open(ARCHIVO, "a", newline="", encoding="utf-8-sig") as archivo:
        escritor = csv.DictWriter(archivo, fieldnames=CAMPOS)

        if archivo.tell() == 0:
            escritor.writeheader()

        escritor.writerow(venta)

    ventas.append(venta)
    print(f"Venta guardada. Ganancia: S/ {venta['ganancia']:.2f}")


def ver_resumen():
    if not ventas:
        print("Todavia no hay ventas.")
        return

    ingresos = sum(float(v["ingreso"]) for v in ventas)
    costos = sum(float(v["gasto"]) for v in ventas)
    ganancias = sum(float(v["ganancia"]) for v in ventas)

    print(f"\nVentas registradas: {len(ventas)}")
    print(f"Ingresos: S/ {ingresos:.2f}")
    print(f"Costos: S/ {costos:.2f}")
    print(f"Ganancias: S/ {ganancias:.2f}")


while True:
    print("\n=== CONTROL DE VENTAS ===")
    print("1. Registrar venta")
    print("2. Ver resumen")
    print("3. Salir")

    opcion = input("Elige una opcion: ").strip()

    if opcion == "1":
        registrar_venta()
    elif opcion == "2":
        ver_resumen()
    elif opcion == "3":
        print("Programa finalizado.")
        break
    else:
        print("Opcion no valida.")